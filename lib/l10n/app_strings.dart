/// Uygulamanın desteklediği diller.
///
/// Sıra kalıcıdır: tercih [SettingsService] içinde sıra numarası olarak
/// saklandığı için yeni diller yalnızca sona eklenmelidir.
enum AppLanguage { system, turkish, english }

/// Basit, bağımlılıksız yerelleştirme.
///
/// Metinler noktalı anahtarlarla aranır: `t('common.cancel')`.
/// Değişken içeren metinlerde `{ad}` yer tutucuları kullanılır ve
/// `t('x.y', {'ad': 'değer'})` biçiminde doldurulur.
///
/// Dil [AppLanguage.system] ise cihazın dili Türkçe olduğunda Türkçe,
/// aksi hâlde İngilizce kullanılır.
class Strings {
  Strings._();

  /// Etkin dil tercihi. [SettingsService] tarafından ayarlanır.
  static AppLanguage language = AppLanguage.system;

  /// Dil kodundan metin tablosuna eşleme.
  static const Map<String, Map<String, String>> _tables = {
    'tr': _tr,
    'en': _en,
  };

  /// Etkin dil kodu.
  ///
  /// [AppLanguage.system] seçiliyken cihazın dili destekleniyorsa o,
  /// desteklenmiyorsa İngilizce kullanılır.
  static String get code {
    switch (language) {
      case AppLanguage.turkish:
        return 'tr';
      case AppLanguage.english:
        return 'en';
      case AppLanguage.system:
        final device = PlatformDispatcher.instance.locale.languageCode;
        return _tables.containsKey(device) ? device : 'en';
    }
  }

  static bool get isTurkish => code == 'tr';

  /// Bir dilin anahtar kümesi (yalnızca testler için).
  @visibleForTesting
  static Set<String> debugKeys(String code) =>
      (_tables[code] ?? const <String, String>{}).keys.toSet();

  /// Bir dildeki ham metin (yalnızca testler için).
  @visibleForTesting
  static String debugValue(String code, String key) =>
      _tables[code]?[key] ?? '';

  static String get(String key, [Map<String, Object?>? args]) {
    // Bir dilde eksik anahtar olursa İngilizceye düşülür; hiçbir ekranda
    // ham anahtar görünmez.
    final table = _tables[code] ?? _en;
    var value = table[key] ?? _en[key] ?? _tr[key] ?? key;
    if (args != null) {
      args.forEach((name, replacement) {
        value = value.replaceAll('{$name}', '$replacement');
      });
    }
    return value;
  }

